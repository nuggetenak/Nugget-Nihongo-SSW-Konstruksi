// ─── data/genba-phrases.js — 現場日本語 ───────────────────────────────────────
// UI_UX_PLAN item 103. The deck teaches 1,626 terms and, measured 2026-09-07,
// **3 of its 1,418 usage sentences are in an imperative or request form.** A
// worker who knows every card still has not met `ここ持ってて` — and `ここ持ってて`
// is what they will actually hear on their first morning.
//
// So this file is not more vocabulary. It is the register: what a mandor says to
// you, clipped the way it is really said, and what you say back.
//
// ── WHY THE ENTRIES COME IN TWO DIRECTIONS ──────────────────────────────────
// `speaker` is load-bearing, not a label. An instruction arrives *at* you and
// the skill is doing the right thing; a report leaves *from* you and the skill
// is finding the right words. Those are different drills over the same content,
// and collapsing them would teach a learner to produce a foreman's lines —
// sentences they will never have cause to say.
//
//   speaker: 'shokucho'  — you hear it. `answer`/`traps` are Indonesian ACTIONS.
//   speaker: 'sagyouin'  — you say it.  `answer`/`traps` are Japanese PHRASES.
//
// genba-phrases.test.js asserts that split by character class, so an entry
// cannot quietly drift into offering a Japanese phrase where an action belongs.
//
// ── FIELDS ──────────────────────────────────────────────────────────────────
//   jp         the phrase as spoken — contracted, particles dropped, as heard
//   id_text    what it means
//   polite     the ですます form of the same thing, or null if `jp` already is.
//              The pair is the point: the plain form is what reaches you, the
//              polite form is what you are safe saying back.
//   situation  when this is said. The drill stem for 'sagyouin'; context for
//              'shokucho'.
//   answer     the correct option
//   traps      three wrong ones, same kind as `answer`
//   reply      what you say in response, or null where none is expected
//   note       the one thing that trips up an Indonesian speaker. Grammar only
//              where the grammar changes the action — 持ってくる vs 持っていく
//              point in opposite directions, and on a site that matters.
//
// Furigana follows the corpus rule: one word per marker, reading never wider
// than its own base. audit:text covers this file like every other under
// src/data/.
// ─────────────────────────────────────────────────────────────────────────────

